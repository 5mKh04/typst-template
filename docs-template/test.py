# Mọi con số 30000 bị gõ trực tiếp ở khắp nơi
print("Giá 1 ly trà sữa là: 30000 VNĐ")
print("Tổng tiền 3 ly là:", 30000 * 3, "VNĐ")
print("Tiền sau khi giảm 10% là:", (30000 * 3) * 0.9, "VNĐ")

